#!/usr/bin/env bash
# Writes a release's staging migration script (DEPLOYMENT.md §9): the idempotent SQL `dotnet ef migrations script
# --idempotent` generates from the committed migrations, then the synthetic account's seed
# (scripts/sql/staging-seed.sql), then a closing SELECT whose output scripts/migrate.sh looks for, so a run that
# executed nothing cannot pass. It then refuses the script unless it is non-destructive (check-migration-sql.sh).
# Run from the repository root after `dotnet tool restore` and a build of the API (`--no-build` reuses it).
#
# Usage: scripts/migration-script.sh <version> <output.sql> [--no-build]
set -euo pipefail
version="${1:?usage: migration-script.sh <version> <output.sql> [--no-build]}"
out="${2:?usage: migration-script.sh <version> <output.sql> [--no-build]}"
build_flag="${3:-}"
case "$version" in
  *[!0-9A-Za-z.-]*|'') echo "::error::migration-script: '$version' is not a version" >&2; exit 2 ;;
esac
here="$(cd "$(dirname "$0")" && pwd)"

ef_out="$(mktemp)"
trap 'rm -f "$ef_out"' EXIT
# shellcheck disable=SC2086 # build_flag is empty or one flag
dotnet tool run dotnet-ef migrations script --idempotent $build_flag --configuration Release \
  --project src/ApiaryCopilot.Infrastructure --startup-project src/ApiaryCopilot.Api --output "$ef_out"
[[ -s "$ef_out" ]] || { echo "::error::migration-script: dotnet ef wrote no script" >&2; exit 1; }

{
  printf -- '-- Apiary-Keeper %s: the staging migration script, generated by scripts/migration-script.sh.\n' "$version"
  printf -- '-- The committed migrations as idempotent SQL (dotnet ef migrations script --idempotent), then the synthetic\n'
  printf -- '-- account seed. Every part is safe to run again. Staging only (DEPLOYMENT.md section 9).\n\n'
  # EF writes a UTF-8 byte-order mark, a syntax error once it is no longer the file's first byte.
  LC_ALL=C sed -e '1s/^\xEF\xBB\xBF//' -e 's/\r$//' "$ef_out"
  printf '\n'
  tr -d '\r' <"$here/sql/staging-seed.sql"
  # Built from parts, so the line it prints appears nowhere in the script's own text.
  printf "\nSELECT concat('apiary-copilot-migration-', 'applied ', '%s') AS migration;\n" "$version"
} >"$out"

bash "$here/check-migration-sql.sh" "$out"
echo "migration-script: wrote $out"
